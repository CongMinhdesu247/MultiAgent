"""Dependency-free workspace tooling. Requires Python 3.11 or newer."""
import argparse
import json
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GATES = ("lint", "typecheck", "test", "build", "smoke")
KINDS = ("web", "mobile", "desktop", "fullstack")


def project_path(root, slug):
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise ValueError("Use a lowercase slug, e.g. my-product")
    base = (root / "projects").resolve()
    path = (base / slug).resolve()
    if path.parent != base:
        raise ValueError("Project must be inside projects/")
    return path


def init_project(root, slug, kind):
    if kind not in KINDS:
        raise ValueError("Unsupported product kind")
    path = project_path(root, slug)
    if path.exists():
        raise ValueError(f"Refusing to overwrite existing project: {path}")
    templates = root / "templates" / "project"
    if not templates.is_dir():
        raise ValueError("Missing project templates")
    path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(templates, path)
    manifest = {"version": 1, "name": slug, "kind": kind,
                "checks": dict.fromkeys(GATES)}
    (path / "factory.project.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"CREATED {path}\nPlanning workspace only; scaffold the application next.")
    return path


def sync_agents(root, check=False):
    """Use existing VS Code role bodies as the single source of truth."""
    out = root / ".codex" / "agents"
    problems = []
    sources = sorted((root / ".github" / "agents").glob("*.agent.md"))
    if not sources:
        raise ValueError("No source agents found")
    for source in sources:
        raw = source.read_text(encoding="utf-8")
        parts = raw.split("---", 2)
        if len(parts) != 3 or parts[0].strip():
            raise ValueError(f"Invalid frontmatter: {source}")
        description = next((line.split(":", 1)[1].strip()
                            for line in parts[1].splitlines()
                            if line.startswith("description:")), "")
        if not description or not parts[2].strip():
            raise ValueError(f"Missing description or role body: {source}")
        name = source.name.removesuffix(".agent.md")
        # JSON basic strings are compatible with TOML for these ASCII fields.
        body = parts[2].strip()
        if "'''" in body:
            raise ValueError(f"Role contains unsupported TOML delimiter: {source}")
        content = ("# Generated by tools/factory.py sync-agents; edit .github/agents instead.\n"
                   f"name = {json.dumps(name)}\n"
                   f"description = {json.dumps(description)}\n"
                   f"developer_instructions = '''\n{body}\n'''\n")
        tomllib.loads(content)
        target = out / f"{name}.toml"
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            problems.append(str(target.relative_to(root)))
            if not check:
                out.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
    # Never silently delete manually maintained agent files.
    expected = {p.name.removesuffix(".agent.md") for p in sources}
    for target in out.glob("*.toml"):
        if target.stem not in expected:
            raise ValueError(f"Unexpected Codex agent; reconcile manually: {target}")
    if check and problems:
        raise ValueError("Agent definitions out of sync: " + ", ".join(problems))
    print(f"OK {len(sources)} agent definitions" + (" synchronized" if not check else " in sync"))


def doctor(root):
    required = ["AGENTS.md", "README.md", "docs/WORKFLOW.md",
                "templates/project/AGENTS.md", ".github/copilot-instructions.md"]
    for name in required:
        file = root / name
        if not file.is_file() or not file.read_text(encoding="utf-8").strip():
            raise ValueError(f"Missing or empty: {name}")
    config = tomllib.loads((root / ".codex/config.toml").read_text(encoding="utf-8"))
    if config["agents"]["max_concurrent_threads_per_session"] != 3:
        raise ValueError("Unexpected worker limit")
    json.loads((root / ".vscode/tasks.json").read_text(encoding="utf-8"))
    sync_agents(root, check=True)
    print(f"OK Python {sys.version.split()[0]}")
    for command in ("git", "node", "npm", "codex", "flutter", "dart", "java", "adb", "dotnet", "cargo"):
        found = shutil.which(command)
        print(f"{'FOUND' if found else 'NOT FOUND ON PATH'} {command}" + (f": {found}" if found else ""))
    print("Factory configuration OK. SDK availability is informational; product readiness is separate.")


def check_command(path, spec):
    if not isinstance(spec, dict):
        raise ValueError("Check must be an object or null")
    if set(spec) == {"not_applicable"}:
        if not isinstance(spec["not_applicable"], str) or not spec["not_applicable"].strip():
            raise ValueError("not_applicable requires a reason")
        return None
    argv = spec.get("argv")
    if not isinstance(argv, list) or not argv or any(
            not isinstance(arg, str) or not arg or "\x00" in arg for arg in argv):
        raise ValueError("argv must be a nonempty array of nonempty strings")
    cwd = spec.get("cwd", ".")
    if not isinstance(cwd, str):
        raise ValueError("cwd must be a relative path")
    relative = Path(cwd)
    directory = (path / relative).resolve()
    if relative.is_absolute() or not directory.is_relative_to(path.resolve()) or not directory.is_dir():
        raise ValueError("cwd must be an existing directory inside the project")
    timeout = spec.get("timeout_seconds", 600)
    if type(timeout) is not int or not 1 <= timeout <= 3600:
        raise ValueError("timeout_seconds must be between 1 and 3600")
    return argv, directory, timeout


def verify(root, slug, only=None):
    path = project_path(root, slug)
    manifest = json.loads((path / "factory.project.json").read_text(encoding="utf-8"))
    if not isinstance(manifest, dict) or manifest.get("version") != 1 or manifest.get("kind") not in KINDS:
        raise ValueError("Invalid project manifest version/kind")
    checks = manifest.get("checks")
    if not isinstance(checks, dict) or any(key not in checks for key in GATES):
        raise ValueError("Manifest must declare every required check")
    selected = (only,) if only else GATES
    # Validate the entire requested plan before executing any commands.
    plan = {key: check_command(path, checks[key]) if checks[key] is not None else None
            for key in selected}
    status = 0
    for key in selected:
        spec = checks[key]
        if spec is None:
            print(f"NOT RUN {key}: no command configured", flush=True)
            status = max(status, 2)
            continue
        if plan[key] is None:
            print(f"N/A {key}: {spec['not_applicable']}", flush=True)
            continue
        argv, directory, timeout = plan[key]
        print(f"RUN {key} cwd={directory} argv={json.dumps(argv)}", flush=True)
        try:
            result = subprocess.run(argv, cwd=directory, timeout=timeout, shell=False)
            code = result.returncode
            print(f"{'PASS' if code == 0 else 'FAIL'} {key}: exit {code}", flush=True)
            if code:
                return 1
        except (OSError, subprocess.TimeoutExpired) as exc:
            print(f"BLOCKED {key}: {exc}", flush=True)
            return 2
    print("Verification finished" + (" (selected check only)" if only else "") +
          "; review manual and target-platform evidence separately.", flush=True)
    return status


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="action", required=True)
    commands.add_parser("doctor", help="Check factory configuration and available tools")
    sync = commands.add_parser("sync-agents", help="Generate Codex roles from VS Code roles")
    sync.add_argument("--check", action="store_true")
    init = commands.add_parser("init", help="Create planning files, not a runnable application")
    init.add_argument("slug")
    init.add_argument("--kind", choices=KINDS, required=True)
    run = commands.add_parser("verify", help="Execute trusted project check commands")
    run.add_argument("slug")
    run.add_argument("--only", choices=GATES)
    args = parser.parse_args()
    try:
        if args.action == "doctor":
            doctor(ROOT)
        elif args.action == "sync-agents":
            sync_agents(ROOT, args.check)
        elif args.action == "init":
            init_project(ROOT, args.slug, args.kind)
        elif args.action == "verify":
            return verify(ROOT, args.slug, args.only)
    except (ValueError, OSError, KeyError, TypeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
